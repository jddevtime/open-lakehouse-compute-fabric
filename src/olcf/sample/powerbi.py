"""The SYNTHETIC Power BI scanner result of the sample: a semantic model and a report over the sample's gold tables.

**This document is invented.** It is not an export from a Power BI / Fabric tenant and no tenant ever saw it; every identifier in it is a deterministic made-up GUID. It exists so
that a freshly installed sample shows what OLCF Intelligence does with Power BI content: *Where does the number in the Revenue visual come from?* is answered end to end,
report -> visual -> measure -> DAX -> semantic model table -> gold table -> notebook -> silver table -> raw files, with nothing inserted by hand: the link from the model's tables to
the sample's real lakehouse tables is formed by the same analyzers and the same name resolution that link a tenant's models to its lakehouses.

What it contains (all of it labelled :data:`SYNTHETIC_LABEL`, in the source name, the workspace name, the model, the report and a top-level ``x-olcf-synthetic`` key):

* a workspace holding the semantic model *Retail Sales Model* (Direct Lake style: every table is a ``Sql.Database`` read of one gold table of the lakehouse, the way a Direct Lake
  expression names its SQL endpoint) with measures such as ``Total Revenue = SUM('Daily Sales'[net_revenue])``;
* the report *Retail Sales Report* bound to that model, with two pages and visuals that use the measures. The Power BI admin scanner does not return visuals, so the report's PBIR
  parts are attached under the OLCF extension key ``olcfReportDefinition`` (see ``olcf.intelligence.discovery.scanner_import``).

``schemas/sample-retail-powerbi-scan.json`` is this document for the default workspace and lakehouse names (generated by ``python -m olcf.sample.generate --write-schemas``; a
test fails when the committed file drifts).
"""

from __future__ import annotations

import uuid
from typing import Any

from olcf.sample import spec

SYNTHETIC_LABEL = "synthetic example – not from a real tenant"
SOURCE_NAME = f"Sample Retail (synthetic Power BI scan; {SYNTHETIC_LABEL})"
WORKSPACE_NAME = f"Sample Retail ({SYNTHETIC_LABEL})"
MODEL_NAME = "Retail Sales Model"
REPORT_NAME = "Retail Sales Report"
ENDPOINT = "synthetic-sample.datawarehouse.fabric.microsoft.com"
REPORT_DEFINITION_KEY = "olcfReportDefinition"
_NAMESPACE = uuid.UUID("0c5f2f0e-5a5e-4c6e-9d57-5a0e6f1f0a11")
_PBI_TYPES = {"long": "Int64", "int": "Int64", "double": "Double", "string": "String", "date": "DateTime", "timestamp": "DateTime", "boolean": "Boolean"}

#: model table -> (gold table of the lakehouse, [(measure, DAX)])
MODEL_TABLES: dict[str, tuple[str, list[tuple[str, str]]]] = {
    "Daily Sales": ("gold_daily_sales", [
        ("Total Revenue", "SUM('Daily Sales'[net_revenue])"),
        ("Gross Revenue", "SUM('Daily Sales'[gross_revenue])"),
        ("Total Profit", "SUM('Daily Sales'[profit])"),
        ("Total Orders", "SUM('Daily Sales'[orders])"),
        ("Average Order Value", "DIVIDE([Total Revenue], [Total Orders])"),
        ("Gross Margin %", "DIVIDE([Total Profit], [Total Revenue])"),
        ("Discount Amount", "[Gross Revenue] - [Total Revenue]"),
    ]),
    "Category Summary": ("gold_category_summary", [
        ("Category Revenue", "SUM('Category Summary'[net_revenue])"),
        ("Category Profit", "SUM('Category Summary'[profit])"),
    ]),
    "Customer LTV": ("gold_customer_ltv", [
        ("Average Lifetime Revenue", "AVERAGE('Customer LTV'[lifetime_revenue])"),
        ("Customers", "DISTINCTCOUNT('Customer LTV'[customer_id])"),
    ]),
}

#: report visuals: (page, visual id, title, visual type, [(role, "Table", "Field", "Measure"|"Column")])
VISUALS: list[tuple[str, str, str, str, list[tuple[str, str, str, str]]]] = [
    ("overview", "revenue", "Revenue (card)", "card", [("Values", "Daily Sales", "Total Revenue", "Measure")]),
    ("overview", "profit", "Profit (card)", "card", [("Values", "Daily Sales", "Total Profit", "Measure")]),
    ("overview", "orders", "Orders (card)", "card", [("Values", "Daily Sales", "Total Orders", "Measure")]),
    ("overview", "aov", "Average order value (card)", "card", [("Values", "Daily Sales", "Average Order Value", "Measure")]),
    ("overview", "margin", "Gross margin (card)", "card", [("Values", "Daily Sales", "Gross Margin %", "Measure")]),
    ("overview", "revenue_by_day", "Revenue by day (line)", "lineChart", [("Category", "Daily Sales", "sale_date", "Column"), ("Y", "Daily Sales", "Total Revenue", "Measure")]),
    ("overview", "revenue_by_category", "Revenue by category (bar)", "barChart", [("Category", "Category Summary", "category", "Column"),
                                                                           ("Y", "Category Summary", "Category Revenue", "Measure")]),
    ("customers", "ltv", "Average lifetime revenue (card)", "card", [("Values", "Customer LTV", "Average Lifetime Revenue", "Measure")]),
    ("customers", "ltv_by_segment", "Customers by value segment (bar)", "barChart", [("Category", "Customer LTV", "ltv_segment", "Column"), ("Y", "Customer LTV", "Customers", "Measure")]),
]


def guid(name: str) -> str:
    """A deterministic made-up GUID for ``name`` (the same name always gives the same id, so re-importing the document changes nothing)."""
    return str(uuid.uuid5(_NAMESPACE, name))


WORKSPACE_ID = guid("workspace")
MODEL_ID = guid("semantic-model")
REPORT_ID = guid("report")
DATASOURCE_ID = guid("datasource")


def _columns(gold: str) -> list[dict[str, Any]]:
    return [{"name": c["name"], "dataType": _PBI_TYPES[c["type"]], "isHidden": False, "columnType": "Data"} for c in spec.TABLES[gold]["columns"]]


def _m_source(lakehouse_name: str, gold: str) -> str:
    return (f'let\n    Source = Sql.Database("{ENDPOINT}", "{lakehouse_name}"),\n    Data = Source{{[Schema = "dbo", Item = "{gold}"]}}[Data]\nin\n    Data')


def semantic_model(lakehouse_name: str = spec.LAKEHOUSE) -> dict[str, Any]:
    """The ``datasets[]`` entry of the scan result: tables with columns, measures and the M expression that reads the gold table."""
    tables = []
    for name, (gold, measures) in MODEL_TABLES.items():
        tables.append({"name": name, "isHidden": False, "description": f"Direct Lake style table over {lakehouse_name}.{gold} ({SYNTHETIC_LABEL})", "columns": _columns(gold),
                       "measures": [{"name": m, "expression": dax, "isHidden": False} for m, dax in measures], "source": [{"expression": _m_source(lakehouse_name, gold)}]})
    return {"id": MODEL_ID, "name": MODEL_NAME, "configuredBy": "synthetic.owner@example.com", "targetStorageMode": "DirectLake", "contentProviderType": "SyntheticExample",
            "createdDate": "2026-01-01T00:00:00.000", "tables": tables, "expressions": [], "datasourceUsages": [{"datasourceInstanceId": DATASOURCE_ID}],
            "upstreamDataflows": [], "users": []}


def _field(kind: str, table: str, name: str) -> dict[str, Any]:
    return {kind: {"Expression": {"SourceRef": {"Entity": table}}, "Property": name}}


def report_parts(workspace_name: str = WORKSPACE_NAME) -> dict[str, Any]:
    """The PBIR parts of the report (``definition.pbir``, report, pages and one ``visual.json`` per visual)."""
    parts: dict[str, Any] = {
        "definition.pbir": {"version": "4.0", "datasetReference": {"byConnection": {
            "connectionString": f"Data Source=powerbi://api.powerbi.com/v1.0/myorg/{workspace_name};initial catalog={MODEL_NAME};semanticmodelid={MODEL_ID}",
            "pbiModelDatabaseName": MODEL_ID, "connectionType": "pbiServiceXmlaStyleLive"}}},
        "definition/version.json": {"version": "2.0.0"},
        "definition/report.json": {"themeCollection": {"baseTheme": {"name": "CY24SU10"}}, "description": f"{REPORT_NAME} ({SYNTHETIC_LABEL})"},
        "definition/pages/pages.json": {"pageOrder": ["overview", "customers"], "activePageName": "overview"},
        "definition/pages/overview/page.json": {"name": "overview", "displayName": "Sales overview", "displayOption": "FitToPage", "width": 1280, "height": 720},
        "definition/pages/customers/page.json": {"name": "customers", "displayName": "Customer value", "displayOption": "FitToPage", "width": 1280, "height": 720},
    }
    for i, (page, vid, title, vtype, fields) in enumerate(VISUALS):
        parts[f"definition/pages/{page}/visuals/{vid}/visual.json"] = {
            "name": vid, "position": {"x": 20 + (i % 4) * 300, "y": 20 + (i // 4) * 200, "width": 280, "height": 180},
            "visual": {"visualType": vtype,
                       "query": {"queryState": {role: {"projections": [{"field": _field(kind, table, field), "queryRef": f"{table}.{field}"} for r2, table, field, kind in fields if r2 == role]}
                                                for role in dict.fromkeys(r for r, *_ in fields)}},
                       "visualContainerObjects": {"title": [{"properties": {"text": {"expr": {"Literal": {"Value": f"'{title}'"}}}}}]}}}
    return parts


def scan_document(lakehouse_name: str = spec.LAKEHOUSE, workspace_name: str = WORKSPACE_NAME) -> dict[str, Any]:
    """The whole scan result (``{"workspaces": [...], "datasourceInstances": [...]}``) for a lakehouse of that name, labelled synthetic everywhere."""
    report = {"reportType": "PowerBIReport", "id": REPORT_ID, "name": REPORT_NAME, "datasetId": MODEL_ID, "createdDateTime": "2026-01-01T00:00:00.000",
              "modifiedDateTime": "2026-01-01T00:00:00.000", "modifiedBy": "synthetic.owner@example.com", "createdBy": "synthetic.owner@example.com", "users": [],
              REPORT_DEFINITION_KEY: report_parts(workspace_name)}
    workspace = {"id": WORKSPACE_ID, "name": workspace_name, "type": "Workspace", "state": "Active", "isOnDedicatedCapacity": False, "reports": [report], "dashboards": [],
                 "datasets": [semantic_model(lakehouse_name)], "dataflows": [], "datamarts": [], "users": []}
    instance = {"datasourceType": "Sql", "connectionDetails": {"server": ENDPOINT, "database": lakehouse_name}, "datasourceId": DATASOURCE_ID, "gatewayId": None}
    return {"x-olcf-synthetic": f"{SYNTHETIC_LABEL}. Made up for the OLCF sample; nothing in this document was read from a Power BI or Fabric tenant.",
            "workspaces": [workspace], "datasourceInstances": [instance], "misconfiguredDatasourceInstances": []}
