"""Service definitions for running OLCF at login / boot: launchd (macOS), systemd (Linux), Task Scheduler (Windows).

The *generators* here are pure functions (no I/O) so they can be tested byte for byte; :mod:`olcf.cli.commands.service` writes the files and
drives ``launchctl`` / ``systemctl`` / ``schtasks`` (all real, non-prompting system tools).  The units start ``olcf serve`` in the foreground,
so the service manager supervises, restarts and stops it with a normal SIGTERM (graceful shutdown).

Per-user services need no administrator rights on any platform.  The macOS LaunchAgent deliberately starts the *managed* Python of the
installation, never ``/usr/bin/python3``.
"""

from __future__ import annotations

import plistlib
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from xml.sax.saxutils import escape

LABEL = "org.olcf.server"
UNIT_NAME = "olcf.service"
TASK_NAME = "OLCF Server"


@dataclass
class ServiceSpec:
    """Everything a service definition needs."""

    command: list[str]                       # absolute program + arguments, starting ``olcf serve`` in the foreground
    data_dir: Path
    log_dir: Path
    env: dict[str, str] = field(default_factory=dict)
    description: str = "Open Lakehouse Compute Fabric server"
    system: bool = False                     # systemd system unit (needs root) instead of a user unit
    user: str | None = None                  # User= of a system unit
    group: str | None = None


def serve_command(launcher: list[str], data_dir: Path, *, host: str | None = None, port: int | None = None, extra: list[str] | None = None) -> list[str]:
    cmd = [*launcher, "--data-dir", str(data_dir), "serve"]
    if host:
        cmd += ["--host", host]
    if port:
        cmd += ["--port", str(port)]
    return cmd + list(extra or [])


# --------------------------------------------------------------------------------------------- launchd
def render_launchd(spec: ServiceSpec) -> bytes:
    """A per-user LaunchAgent plist (``~/Library/LaunchAgents/org.olcf.server.plist``)."""
    env = {"PATH": "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin", "OLCF_DATA_DIR": str(spec.data_dir), "PYTHONUNBUFFERED": "1", **spec.env}
    doc = {
        "Label": LABEL,
        "ProgramArguments": list(spec.command),
        "WorkingDirectory": str(spec.data_dir),
        "EnvironmentVariables": env,
        "RunAtLoad": True,
        "KeepAlive": {"SuccessfulExit": False},
        "ThrottleInterval": 10,
        "ExitTimeOut": 30,
        "ProcessType": "Background",
        "StandardOutPath": str(spec.log_dir / "launchd.out.log"),
        "StandardErrorPath": str(spec.log_dir / "launchd.err.log"),
    }
    return plistlib.dumps(doc, sort_keys=True)


# --------------------------------------------------------------------------------------------- systemd
def _q(arg: str) -> str:
    """systemd ExecStart quoting: plain tokens stay bare, anything else is double-quoted with \\ and \" escaped; ``%`` is doubled (specifiers)."""
    arg = arg.replace("%", "%%")
    if arg and all(c.isalnum() or c in "/._-=:@+," for c in arg):
        return arg
    return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_systemd(spec: ServiceSpec) -> str:
    """A systemd unit.  User units are ``WantedBy=default.target``; system units are hardened (read-only OS, private /tmp, no new privileges)."""
    lines = [
        "# Generated by `olcf service install`; edit with `systemctl edit olcf` rather than this file.",
        "[Unit]",
        f"Description={spec.description}",
        "After=network-online.target",
        "Wants=network-online.target",
        "StartLimitIntervalSec=300",
        "StartLimitBurst=5",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={spec.data_dir}",
        f"Environment=OLCF_DATA_DIR={_q(str(spec.data_dir))}",
        "Environment=PYTHONUNBUFFERED=1",
    ]
    for k, v in sorted(spec.env.items()):
        if k in {"OLCF_DATA_DIR", "PYTHONUNBUFFERED"}:
            continue
        lines.append(f"Environment={_q(f'{k}={v}')}")
    lines += [
        "ExecStart=" + " ".join(_q(a) for a in spec.command),
        "Restart=on-failure",
        "RestartSec=5",
        "TimeoutStopSec=45",
        "KillMode=mixed",
        "KillSignal=SIGTERM",
        "NoNewPrivileges=true",
        "PrivateTmp=true",
        "ProtectKernelTunables=true",
        "ProtectControlGroups=true",
        "RestrictSUIDSGID=true",
        "LockPersonality=true",
    ]
    if spec.system:
        if spec.user:
            lines.append(f"User={spec.user}")
        if spec.group:
            lines.append(f"Group={spec.group or spec.user}")
        lines += ["ProtectSystem=strict", "ProtectHome=read-only", f"ReadWritePaths={_q(str(spec.data_dir))}", "UMask=0077", "", "[Install]", "WantedBy=multi-user.target"]
    else:
        lines += ["UMask=0077", "", "[Install]", "WantedBy=default.target"]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------------------------- Windows Task Scheduler
def render_windows_task(spec: ServiceSpec, *, user: str = "") -> str:
    """Task Scheduler XML: start at logon of the installing user, restart on failure, no time limit, runs without a console window."""
    prog, args = spec.command[0], spec.command[1:]
    arglist = " ".join(_win_quote(a) for a in args)
    uid = f"<UserId>{escape(user)}</UserId>" if user else ""
    return f"""<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>{escape(spec.description)}</Description><Author>OLCF</Author></RegistrationInfo>
  <Triggers><LogonTrigger><Enabled>true</Enabled>{uid}</LogonTrigger></Triggers>
  <Principals><Principal id="Author"><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>true</Hidden>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <RestartOnFailure><Interval>PT1M</Interval><Count>10</Count></RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{escape(prog)}</Command>
      <Arguments>{escape(arglist)}</Arguments>
      <WorkingDirectory>{escape(str(spec.data_dir))}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
"""


def _win_quote(arg: str) -> str:
    return f'"{arg}"' if (not arg or any(c in arg for c in ' \t"')) else arg


# --------------------------------------------------------------------------------------------- locations
def launchd_path(home: Path) -> Path:
    return home / "Library" / "LaunchAgents" / f"{LABEL}.plist"


def systemd_path(home: Path, system: bool) -> Path:
    return Path("/etc/systemd/system") / UNIT_NAME if system else home / ".config" / "systemd" / "user" / UNIT_NAME


def describe(command: list[str]) -> str:
    return " ".join(shlex.quote(c) for c in command)
