def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file is stale")
    ap.add_argument("--only", default="", help="comma separated subset: cli,configuration,permissions,health-checks,errors,events,mcp-tools")
    args = ap.parse_args()
    only = {s for s in args.only.split(",") if s}
    sys.path.insert(0, str(SRC))
    import os

    os.environ.setdefault("OLCF_DATA_DIR", tempfile.mkdtemp(prefix="olcf-refdoc-"))
    app = None
    if not only or only & {"configuration", "health-checks"}:
        app = _build_app()
    jobs = {
        "cli": gen_cli,
        "configuration": lambda: gen_configuration(app),
        "permissions": gen_permissions,
        "health-checks": lambda: gen_health(app),
        "errors": gen_errors,
        "events": gen_events,
        "mcp-tools": gen_mcp_tools,
    }
    stale = False
    for name, fn in jobs.items():
        if only and name not in only:
            continue
        text = fn()
        path = OUT / f"{name}.md"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{path} is out of date", file=sys.stderr)
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path} ({len(text.splitlines())} lines)")
    return 1 if stale else 0


