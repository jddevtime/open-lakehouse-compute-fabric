def _sample_env_value(annotation: Any, default: Any) -> tuple[str, Any]:
    """An environment value (string) and the Python value it must produce, different from the default, for one settings field."""
    import typing

    origin = typing.get_origin(annotation)
    args = [a for a in typing.get_args(annotation) if a is not type(None)]
    base = args[0] if origin in (typing.Union, getattr(__import__("types"), "UnionType", None)) and args else annotation
    if base is bool:
        return ("false" if default else "true"), (not default)
    if base is int:
        return str(int(default or 0) + 7), int(default or 0) + 7
    if base is float:
        return str(float(default or 0) + 0.5), float(default or 0) + 0.5
    if typing.get_origin(base) is tuple:
        return "[3, 4]", (3, 4)
    if typing.get_origin(base) is list:
        return '["a", "b"]', ["a", "b"]
    if base is Path:
        return "/tmp/olcf-env-probe", Path("/tmp/olcf-env-probe")  # noqa: S108
    return "probe-value", "probe-value"


def _is_model(ann: Any) -> bool:
    from pydantic import BaseModel

    return inspect.isclass(ann) and issubclass(ann, BaseModel)


def _sections(model: Any, prefix: str = "") -> Iterator[tuple[str, Any]]:
    """``(dotted section name, model class)`` for every settings section, nested sections (``runtime.trust``) after their parent."""
    for name, field in model.model_fields.items():
        if _is_model(field.annotation):
            yield f"{prefix}{name}", field.annotation
            yield from _sections(field.annotation, f"{prefix}{name}.")


def _leaf_fields(model: Any, prefix: str = "") -> Iterator[tuple[str, Any, Any]]:
    """``(dotted key, field, owning model)`` for every non-section field of ``model``, at any nesting depth."""
    for name, field in model.model_fields.items():
        if _is_model(field.annotation):
            yield from _leaf_fields(field.annotation, f"{prefix}{name}.")
        else:
            yield f"{prefix}{name}", field, model


def _env_name(dotted: str) -> str:
    return "OLCF_" + dotted.replace(".", "__").upper()


def verify_env_mapping() -> tuple[int, list[str]]:
    """Set ``OLCF_<KEY>`` / ``OLCF_<SECTION>__<KEY>`` for every process setting, build ``Settings`` and check the value arrived.

    Returns ``(settings checked, problems)``.  This is what makes the "Environment variable" column of the configuration reference a verified fact.
    """
    import os

    from olcf.core.config import Settings

    checked = 0
    problems: list[str] = []
    saved = {k: v for k, v in os.environ.items() if k.startswith("OLCF_") and "__" in k or k in {f"OLCF_{n.upper()}" for n in Settings.model_fields}}
    for k in saved:
        os.environ.pop(k, None)
    try:
        for dotted_key, field, _owner in _leaf_fields(Settings):
            default = field.get_default(call_default_factory=True) if (field.default_factory or field.default is not ...) else None
            targets: list[tuple[str, str | None, Any, Any]] = [(_env_name(dotted_key), dotted_key, field.annotation, default)]
            for env, dotted, annotation, default in targets:
                raw, expected = _sample_env_value(annotation, default)
                os.environ[env] = raw
                try:
                    st = Settings()
                    got: Any = st
                    for part in str(dotted).split("."):
                        got = getattr(got, part)
                    if isinstance(expected, tuple):
                        got = tuple(got)
                    checked += 1
                    if got != expected:
                        problems.append(f"{env}={raw!r} gave {got!r}, expected {expected!r}")
                except Exception as exc:  # noqa: BLE001
                    problems.append(f"{env}={raw!r}: {exc}")
                finally:
                    os.environ.pop(env, None)
    finally:
        os.environ.update(saved)
    return checked, problems


def probe_env_merge() -> bool:
    """True when one ``OLCF_<SECTION>__<KEY>`` variable overrides only that key (the other keys of the section in ``config.toml`` survive)."""
    import os

    from olcf.core.config import load_settings

    with tempfile.TemporaryDirectory(prefix="olcf-envmerge-") as d:
        (Path(d) / "config.toml").write_text('[server]\nhost = "0.0.0.0"\nport = 8470\npublic_url = "https://probe.example"\n', encoding="utf-8")
        old = os.environ.get("OLCF_SERVER__PORT")
        os.environ["OLCF_SERVER__PORT"] = "9123"
        try:
            st = load_settings(d)
        finally:
            if old is None:
                os.environ.pop("OLCF_SERVER__PORT", None)
            else:
                os.environ["OLCF_SERVER__PORT"] = old
        return st.server.port == 9123 and st.server.host == "0.0.0.0" and st.server.public_url == "https://probe.example"  # noqa: S104


