def _schema_type(spec: dict[str, Any]) -> str:
    """One-line type of a JSON Schema property: ``string``, ``integer 1..50``, ``one of up | down | both``, ``array of string``."""
    if "enum" in spec:
        return "one of " + " \\| ".join(f"`{v}`" for v in spec["enum"])
    kind = spec.get("type", "any")
    if kind == "array":
        inner = (spec.get("items") or {}).get("type", "any")
        return f"array of {inner}" + (f" (max {spec['maxItems']})" if "maxItems" in spec else "")
    if kind in ("integer", "number") and ("minimum" in spec or "maximum" in spec):
        return f"{kind} {spec.get('minimum', '')}..{spec.get('maximum', '')}"
    return str(kind)


