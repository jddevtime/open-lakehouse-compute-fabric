def click_tree() -> list[tuple[str, str]]:
    """``[(command path, help text)]`` for the whole click tree, depth first."""
    import click

    sys.path.insert(0, str(SRC))
    from olcf.cli.main import cli as root  # type: ignore[attr-defined]

    out: list[tuple[str, str]] = []

    def walk(cmd: click.Command, path: list[str], parent: click.Context | None) -> None:
        ctx = click.Context(cmd, info_name=path[-1], parent=parent, terminal_width=100, max_content_width=100)
        out.append((" ".join(path), cmd.get_help(ctx)))
        if isinstance(cmd, click.Group):
            for name in cmd.list_commands(ctx):
                sub = cmd.get_command(ctx, name)
                if sub is not None and not getattr(sub, "hidden", False):
                    walk(sub, [*path, name], ctx)

    walk(root, ["olcf"], None)
    return out


_USAGE_TOKEN = re.compile(r"\[[^\[\]]*\]|\([^()]*\)|\S+(?: \.\.\.)?")


def normalise_usage(text: str, width: int = 98) -> str:
    """Re-wrap the ``usage:`` paragraph of an argparse help text so that it does not depend on the Python version.

    argparse decides where to break the usage line (and whether the positional arguments start a new line) differently between Python 3.11, 3.12 and 3.13, which made the
    generated page differ by interpreter.  The tokens are kept, and wrapped greedily at ``width`` columns with a hanging indent under the first token after the program name.
    """
    head, sep, rest = text.partition("\n\n")
    if not head.startswith("usage: "):
        return text
    body = " ".join(line.strip() for line in head[len("usage: "):].splitlines())
    tokens = _USAGE_TOKEN.findall(body)
    if not tokens:
        return text
    first = next((i for i, t in enumerate(tokens) if t.startswith("[")), None)  # the program name ends where the optionals begin ("[-h]" is always there)
    if first is None:
        return text
    prog = " ".join(tokens[:first])
    tokens = tokens[first:]
    indent = " " * (len("usage: ") + len(prog) + 1)
    lines: list[str] = []
    cur = "usage: " + prog
    for tok in tokens:
        if len(cur) + 1 + len(tok) > width and cur.strip() != "usage:" and cur != indent:
            lines.append(cur)
            cur = indent + tok
        else:
            cur += " " + tok
    lines.append(cur)
    return "\n".join(lines) + sep + rest


_SHORT_LONG_WITH_VALUE = re.compile(r"^(\s+)(-\w) ([^\s,]+), (--[\w-]+) \3(?=\s|$)", re.MULTILINE)


def normalise_help(text: str) -> str:
    """argparse help text with the Python-version differences removed: the ``usage:`` wrapping and the ``-o FILE, --output FILE`` / ``-o, --output FILE`` spelling (3.13)."""
    text = _SHORT_LONG_WITH_VALUE.sub(r"\1\2, \4 \3", normalise_usage(text))
    # the shorter spelling can now fit left of the help column: argparse then keeps the help on the same line
    lines = text.split("\n")
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        if re.fullmatch(r"  -[^\s].*", line) and "  " not in line[2:] and len(line) <= 22 and nxt.startswith(" " * 24) and not nxt.startswith(" " * 25):
            out.append(line.ljust(24) + nxt.strip())
            i += 2
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def argparse_tree(argv: list[str], depth: int = 0) -> list[tuple[str, str]]:
    """Run ``<argv> -h`` and recurse (one level) into the ``{a,b,c}`` sub-commands listed under "positional arguments"."""
    res = subprocess.run([sys.executable, *argv[1:], "-h"], capture_output=True, text=True, env=_env(), timeout=120, check=False)  # noqa: S603
    if res.returncode != 0:  # never document a traceback as if it were the help text
        raise RuntimeError(f"`{' '.join(argv[1:])} -h` exited {res.returncode}:\n{res.stderr or res.stdout}")
    text = normalise_help((res.stdout or res.stderr).rstrip())
    out = [(_label(argv), text)]
    if depth >= 1:
        return out
    m = re.search(r"positional arguments:\s*\n\s*\{([a-z0-9_,-]+)\}", text)
    if m:
        for sub in m.group(1).split(","):
            out.extend(argparse_tree([*argv, sub], depth + 1))
    return out


def _label(argv: list[str]) -> str:
    names = {
        ("-m", "olcf.worker.main"): "olcf-worker",
        ("-m", "olcf.runtime"): "python -m olcf.runtime",
        ("-m", "olcf.ops.backup"): "python -m olcf.ops.backup",
        ("-m", "olcf.mcp.stdio"): "python -m olcf.mcp.stdio",
        ("-m", "olcf.ops.upgrade"): "python -m olcf.ops.upgrade",
    }
    head = tuple(argv[1:3])
    return " ".join([names.get(head, " ".join(head)), *argv[3:]])


def gen_cli() -> str:
    parts = [GENERATED]
    parts.append(
        "# CLI reference\n\n"
        "The `olcf` command is a thin client of the REST API plus the local lifecycle commands (`init`, `serve`, `doctor`, `service`, `upgrade`, `backup`, `restore`). "
        "The task-oriented introduction is the [CLI guide](../guides/cli.md); this page is the complete option listing, produced from `--help`.\n"
    )
    tree = click_tree()
    parts.append(f"`olcf` has {len(tree) - 1} sub-commands and command groups. Jump to: " + ", ".join(
        f"[`{p}`](#{re.sub(r'[^a-z0-9-]+', '-', p.lower()).strip('-')})" for p, _ in tree if p.count(" ") == 1) + ".\n")
    for path, text in tree:
        level = min(path.count(" ") + 2, 5)
        parts.append(f"{'#' * level} {path}\n\n```text\n{text.rstrip()}\n```\n")
    parts.append("## Other command line tools\n")
    for argv in (
        [sys.executable, "-m", "olcf.worker.main"],
        [sys.executable, "-m", "olcf.runtime"],
        [sys.executable, "-m", "olcf.ops.upgrade"],
        [sys.executable, "-m", "olcf.ops.backup"],
        [sys.executable, "-m", "olcf.mcp.stdio"],
    ):
        for path, text in argparse_tree(argv):
            level = 3 if path.count(" ") <= (1 if path.startswith("olcf-worker") else 2) else 4
            parts.append(f"{'#' * level} {path}\n\n```text\n{text.rstrip()}\n```\n")
    return "\n".join(parts).rstrip() + "\n"


