def _field_comments(source: str) -> dict[tuple[str, str], str]:
    """Map ``(class name, field name)`` to the ``#:`` / inline comments found next to the field."""
    comments: dict[tuple[str, str], str] = {}
    tree = ast.parse(source)
    lines = source.splitlines()
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                bits: list[str] = []
                i = stmt.lineno - 2
                while i >= 0 and lines[i].strip().startswith("#"):
                    bits.insert(0, lines[i].strip().lstrip("#: ").strip())
                    i -= 1
                inline = lines[stmt.lineno - 1].split("#", 1)
                if len(inline) == 2:
                    bits.append(inline[1].strip())
                comments[(node.name, stmt.target.id)] = " ".join(b for b in bits if b)
    return comments


def _fmt_default(v: Any) -> str:
    if v is None:
        return "*(unset)*"
    if isinstance(v, str):
        return f'`"{v}"`' if v else '`""`'
    if isinstance(v, (list, tuple, dict)):
        return f"`{list(v) if isinstance(v, tuple) else v!r}`".replace("(", "[").replace(")", "]") if v else "`[]`"
    return f"`{v!r}`".lower() if isinstance(v, bool) else f"`{v!r}`"


