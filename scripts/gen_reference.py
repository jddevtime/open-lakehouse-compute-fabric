def gen_health(app: Any) -> str:
    ctx = app.state.ctx
    checks = list(ctx.health._checks.values())
    out = [GENERATED, "# Health checks\n"]
    out.append(
        "Every component reports `ok`, `degraded`, `down` or `unknown`. A **quick** check is cheap and runs on every refresh of the overview; a **deep** check performs a real "
        "end-to-end test and returns a list of steps (this is what every *Test connectivity* button in the control panel runs: `POST /v1/admin/health/checks/{name}/test`). "
        "`GET /v1/health` (liveness: the process is up) and `GET /v1/health/ready` (readiness: the database answers and `runtime-trust` is not `down`; otherwise `503` with a fixed body) are the unauthenticated probes for load balancers and orchestrators; `GET /v1/admin/health` is the authenticated snapshot (`admin.health`).\n"
    )
    out.append(f"The following {len(checks)} checks are registered by a control plane built from this source tree. Names with `<...>` are created per runtime or provider.\n")
    out.append("| Check | Category | Deep test | Critical | What it checks |")
    out.append("|---|---|---|---|---|")
    for c in sorted(checks, key=lambda c: (c.category, c.name)):
        name = re.sub(r"^(spark-master):.*$", r"\1:<runtime-id>", c.name)
        out.append(f"| `{name}` | {c.category} | {'yes' if c.deep else 'no'} | {'yes' if c.critical else 'no'} | {c.description} |")
    out.append("")
    # collapse duplicate spark-master rows
    text = "\n".join(out)
    seen: set[str] = set()
    lines = []
    for line in text.splitlines():
        if line.startswith("| `spark-master:<runtime-id>`"):
            if line in seen:
                continue
            seen.add(line)
        lines.append(line)
    return "\n".join(lines).rstrip() + "\n"


