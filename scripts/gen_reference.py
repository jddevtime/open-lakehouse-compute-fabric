    out.append("`x` = granted by the role. `PlatformAdmin` holds every permission.\n")
    short = {n: n for n in role_names}
    out.append("| Permission | Meaning | " + " | ".join(short[n] for n in role_names) + " |")
    out.append("|---|---|" + "---|" * len(role_names))
    for perm, desc in rbac.PERMISSIONS.items():
        cells = []
        for r in roles:
            ps = rbac.ROLE_PERMISSIONS[r]
