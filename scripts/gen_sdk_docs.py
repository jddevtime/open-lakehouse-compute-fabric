"""Generate the SDK reference pages from the code.

Pages written to ``docs/reference/``:

* ``sdk.md``          - the Python client (:class:`olcf.sdk.Client`): every resource group, every public method with its signature, the REST call it
                        makes (read from the method's AST, so it cannot drift) and the first line of its docstring; plus the exception hierarchy.
* ``fabric-sdk.md``   - the ``olcf_fabric`` package that runs inside a Microsoft Fabric notebook (public names, signatures, docstrings, the
                        ``configure()`` options).
* ``fabric-rules.md`` - the compatibility analyzer rule catalogue (``src/olcf/fabric/analyzer/rules/fabric-2.0.yaml``), grouped by class.

Usage::

    PYTHONPATH=src python scripts/gen_sdk_docs.py [--check] [--only sdk,fabric-sdk,fabric-rules]

``--check`` exits 1 when a page on disk differs from what the code would generate.
"""

from __future__ import annotations

import argparse
import ast
import inspect
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "sdk" / "fabric"))
NOTE = "> Generated by `scripts/gen_sdk_docs.py` from the code. Do not edit by hand; regenerate instead.\n"


def _md(text: str) -> str:
    """reStructuredText roles and double backticks of a docstring to Markdown."""
    text = re.sub(r":(?:class|func|meth|mod|exc|attr|data):`~?([^`]+)`", lambda m: "`" + m.group(1).split(".")[-1] + "`", text)
    return text.replace("``", "`")


def _first_line(doc: str | None) -> str:
    if not doc:
        return ""
    para = inspect.cleandoc(doc).split("\n\n")[0]
    return _md(" ".join(para.split()))


def _routes(fn: Any) -> list[str]:
    """``METHOD /path`` for every ``self._call("METHOD", "/path", ...)`` / ``self._c.call(...)`` in the function body."""
    try:
        tree = ast.parse(textwrap.dedent(inspect.getsource(fn)))
    except (OSError, TypeError, SyntaxError):
        return []
    found: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr in {"_call", "call", "request"} and len(node.args) >= 2:
            a, b = node.args[0], node.args[1]
            if isinstance(a, ast.Constant) and isinstance(b, ast.Constant) and isinstance(a.value, str) and isinstance(b.value, str):
                found.append(f"{a.value} /v1{b.value if b.value.startswith('/') else '/' + b.value}")
    return list(dict.fromkeys(found))


def _sig(fn: Any) -> str:
    try:
        sig = inspect.signature(fn)
    except (TypeError, ValueError):
        return "(...)"
    out: list[str] = []
    seen_kw = False
    items = [p for name, p in sig.parameters.items() if name != "self"]
    for i, p in enumerate(items):
        if p.kind is p.KEYWORD_ONLY and not seen_kw and not any(q.kind is q.VAR_POSITIONAL for q in items[:i]):
            out.append("*")
        seen_kw = seen_kw or p.kind is p.KEYWORD_ONLY
        ann = p.annotation
        ann_s = "" if ann is p.empty else (ann if isinstance(ann, str) else getattr(ann, "__name__", str(ann)))
        prefix = "**" if p.kind is p.VAR_KEYWORD else "*" if p.kind is p.VAR_POSITIONAL else ""
        txt = prefix + p.name + (f": {ann_s}" if ann_s else "")
        if p.default is not p.empty:
            txt += (" = " if ann_s else "=") + ("<factory>" if "factory" in repr(p.default) else repr(p.default))
        out.append(txt)
    return "(" + ", ".join(out).replace("builtins.", "") + ")"


def gen_sdk() -> str:
    from olcf.sdk import Client, errors
    from olcf.sdk._resources import _Res

    client = Client("http://127.0.0.1:1", token="x")  # noqa: S106 - a dummy value, nothing is sent
    lines = ["# Python SDK reference", "", NOTE, "",
             "`from olcf.sdk import Client` (synchronous) or `AsyncClient` (same surface, awaitable). Methods return plain `dict`/`list` values decoded from the "
             "REST API; list methods return a `Page` (a `list` with `.next_cursor`). The REST call behind each method is shown so the SDK can be read next to "
             "[the API reference](api.md). Anything without a wrapper is reachable with `client.request(method, path)`.", "",
             "Guide: [Using the SDK](../guides/sdk.md).", "", "## Client", ""]
    for name in ("from_env", "from_context", "login", "logout", "me", "health", "info", "request", "paginate", "set_token", "close"):
        fn = getattr(Client, name, None)
        if fn is None:
            continue
        lines.append(f"- `Client.{name}{_sig(fn)}` - {_first_line(inspect.getdoc(fn))}".rstrip(" -"))
    lines += ["", f"`Client({_sig(Client.__init__)[1:-1]})`", "", "## Resource groups", ""]
    groups = sorted((n, o) for n, o in vars(client).items() if isinstance(o, _Res))
    lines.append("| Attribute | Class | Methods |")
    lines.append("|---|---|---|")
    for n, o in groups:
        meths = [m for m, _ in inspect.getmembers(type(o), inspect.isfunction) if not m.startswith("_")]
        lines.append(f"| `client.{n}` | `{type(o).__name__}` | {len(meths)} |")
    for n, o in groups:
        cls = type(o)
        lines += ["", f"### `client.{n}`", "", _first_line(inspect.getdoc(cls)) if cls.__doc__ else "", ""]
        lines.append("| Method | REST call | Description |")
        lines.append("|---|---|---|")
        for m, fn in sorted(inspect.getmembers(cls, inspect.isfunction)):
            if m.startswith("_"):
                continue
            routes = "<br>".join(f"`{r}`" for r in _routes(fn)) or "-"
            doc = _first_line(inspect.getdoc(fn)).replace("|", "\\|")
            sig = _sig(fn).replace("|", "\\|")
            lines.append(f"| `{m}{sig}` | {routes} | {doc} |")
    lines += ["", "## Errors", "", "All SDK errors derive from `OlcfSdkError`; HTTP errors derive from `ApiError` and carry `status`, `code`, `message`, `remediation` and `correlation_id`.", "",
              "| Exception | Base | Raised for |", "|---|---|---|"]
    for name in sorted(n for n in dir(errors) if n[:1].isupper()):
        obj = getattr(errors, name)
        if inspect.isclass(obj) and issubclass(obj, errors.OlcfSdkError):
            base = obj.__bases__[0].__name__
            lines.append(f"| `{name}` | `{base}` | {_first_line(obj.__doc__).replace('|', chr(92) + '|')} |")
    lines.append("")
    return "\n".join(lines)


def gen_fabric_sdk() -> str:
    import olcf_fabric
    from olcf_fabric import config as cfg

    lines = ["# `olcf-fabric` reference (runs inside a Fabric notebook)", "", NOTE, "",
             f"Package version {olcf_fabric.__version__}. Standard library only; installed with `%pip install olcf-fabric` in a Fabric notebook (or from the wheel "
             "built by `scripts/build_fabric_sdk.sh`). Not a Microsoft product. Guide: [Fabric integration](../guides/fabric-integration.md); what the package assumes "
             "about Fabric: [Fabric assumptions](../guides/fabric-assumptions.md).", "", "## Public API", "", "| Name | Signature | Description |", "|---|---|---|"]
    for name in olcf_fabric.__all__:
        obj = getattr(olcf_fabric, name)
        if name == "__version__":
            continue
        if inspect.isclass(obj) or inspect.isfunction(obj):
            sig = _sig(obj) if inspect.isfunction(obj) or inspect.isclass(obj) else ""
            kind = "class" if inspect.isclass(obj) else "function"
            sig = sig.replace("|", "\\|")
            lines.append(f"| `{name}` ({kind}) | `{name}{sig}` | {_first_line(inspect.getdoc(obj)).replace('|', chr(92) + '|')} |")
        else:
            lines.append(f"| `{name}` | | {_first_line(type(obj).__doc__)} |")
    lines += ["", "## Exceptions", "", "| Exception | Base |", "|---|---|"]
    for name in olcf_fabric.__all__:
        obj = getattr(olcf_fabric, name)
        if inspect.isclass(obj) and issubclass(obj, Exception):
            lines.append(f"| `{name}` | `{obj.__bases__[0].__name__}` |")
    lines += ["", "## Configuration", "", "```python", "import olcf_fabric as olcf", "olcf.configure(endpoint=..., auth=..., ...)", "```", ""]
    fn = cfg.configure
    lines += [f"`configure{_sig(fn)}`", "", _md(inspect.getdoc(fn) or ""), ""]
    for cls_name in ("RemoteRun",):
        cls = getattr(olcf_fabric, cls_name, None)
        if cls is None:
            continue
        lines += [f"## `{cls_name}`", "", _first_line(inspect.getdoc(cls)), "", "| Member | Description |", "|---|---|"]
        for m, f in sorted(inspect.getmembers(cls)):
            if m.startswith("_") or not (inspect.isfunction(f) or isinstance(f, property)):
                continue
            target = f.fget if isinstance(f, property) else f
            sig = "" if isinstance(f, property) else _sig(f).replace("|", "\\|")
            lines.append(f"| `{m}{sig}` | {_first_line(inspect.getdoc(target)).replace('|', chr(92) + '|')} |")
    lines.append("")
    return "\n".join(lines)


def gen_fabric_rules() -> str:
    from olcf.fabric.analyzer import ANALYZER_VERSION, CLASSES, load_ruleset

    rs = load_ruleset()
    d = rs.describe()
    rules = list(rs.rules.values()) if isinstance(rs.rules, dict) else list(rs.rules)
    lines = ["# Fabric compatibility rules", "", NOTE, "",
             f"Analyzer engine {ANALYZER_VERSION}, rule set {d['ruleset_version']} for the runtime families {', '.join(f'`{f}`' for f in d['runtime_families'])}. "
             f"{len(rules)} rules in {len(CLASSES)} classes. The rules are data (`src/olcf/fabric/analyzer/rules/fabric-2.0.yaml`); the engine never guesses: "
             "a `notebookutils` call, import, magic or Spark setting that matches no rule is reported as unknown and blocks the run (fail closed).", "",
             "Guide: [Fabric integration](../guides/fabric-integration.md).", "", "## Classes", "", "| Class | Severity | Meaning | Rules |", "|---|---|---|---|"]
    meaning = {
        "native-portable": "Runs unchanged on the OLCF runtime.",
        "compatibility-shim": "Served by an OLCF shim (`notebookutils`, path resolution).",
        "deterministic-rewrite": "Rewritten by a fixed, visible transformation before execution.",
        "warning": "Runs, but behaviour may differ from Fabric; read the message.",
        "fabric-only-fallback": "Fabric-specific optimisation or feature with no OLCF equivalent; ignored, results do not change.",
        "unsupported": "Cannot run; the job is blocked before execution, with cell, line and remediation (fail closed).",
    }
    from olcf.fabric.analyzer.rules import SEVERITY
    for c in CLASSES:
        n = sum(1 for r in rules if r.cls == c)
        lines.append(f"| `{c}` | {SEVERITY[c]} | {meaning[c]} | {n} |")
    for c in CLASSES:
        group = sorted((r for r in rules if r.cls == c), key=lambda r: r.id)
        if not group:
            continue
        lines += ["", f"## {c}", "", "| Rule | Title | Message | Remediation / shim |", "|---|---|---|---|"]
        for r in group:
            extra = r.remediation or (f"shim `{r.shim}`" if r.shim else "")
            lines.append(f"| `{r.id}` | {r.title.replace('|', chr(92) + '|')} | {r.message.replace('|', chr(92) + '|')} | {extra.replace('|', chr(92) + '|')} |")
    lines.append("")
    return "\n".join(lines)


PAGES = {"sdk": ("sdk.md", gen_sdk), "fabric-sdk": ("fabric-sdk.md", gen_fabric_sdk), "fabric-rules": ("fabric-rules.md", gen_fabric_rules)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated page is stale")
    ap.add_argument("--only", default="", help="comma separated subset: " + ",".join(PAGES))
    args = ap.parse_args(argv)
    wanted = [w for w in args.only.split(",") if w] or list(PAGES)
    stale = 0
    for key in wanted:
        if key not in PAGES:
            print(f"unknown page {key!r}", file=sys.stderr)
            return 2
        fname, fn = PAGES[key]
        text = fn()
        path = OUT / fname
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path.relative_to(ROOT)}  (run scripts/gen_sdk_docs.py)")
                stale += 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}  ({len(text.splitlines())} lines)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
